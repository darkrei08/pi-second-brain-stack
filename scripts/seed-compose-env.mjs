#!/usr/bin/env node

import { randomBytes } from 'node:crypto';
import { chmod, link, lstat, mkdir, open, readFile, unlink } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const defaultOutputPath = resolve(repositoryRoot, '.secrets', 'compose.env');

// Secrets the compose files require and that have no default and no committed
// value. Nothing else belongs in this file: it is loaded after every other
// environment file, so anything duplicated here would shadow the operator's
// committed configuration.
const secretKeys = ['POSTGRES_PASSWORD', 'GATEWAY_TOKEN', 'WEBUI_SECRET_KEY'];

// Host ports are not secrets, but they are pinned here for the same reason: this
// file is loaded last, so the ports an operator picked survive a restart instead
// of falling back to defaults that may already be taken on the host.
const portDefaults = {
  POSTGRES_HOST_PORT: '55432',
  GATEWAY_HOST_PORT: '8080',
  WEBUI_HOST_PORT: '3300'
};
const portKeys = Object.keys(portDefaults);

process.umask(0o077);

function parseArguments(argumentsList) {
  let outputPath = defaultOutputPath;
  for (let index = 0; index < argumentsList.length; index += 1) {
    const argument = argumentsList[index];
    if (argument === '--output' && argumentsList[index + 1] !== undefined) {
      outputPath = resolve(argumentsList[++index]);
    } else {
      throw new Error(`unknown or incomplete argument: ${argument}`);
    }
  }
  return { outputPath };
}

function secureSecret() {
  return randomBytes(32).toString('hex');
}

function validateCompleteEnvironment(content, context) {
  for (const key of secretKeys) {
    const matches = content.match(new RegExp(`^${key}=(.+)$`, 'gmu')) ?? [];
    if (matches.length !== 1) throw new Error(`${context} is incomplete`);
  }
}

async function inspectEnvironmentFile(outputPath) {
  let metadata;
  try {
    metadata = await lstat(outputPath);
  } catch (error) {
    if (error?.code === 'ENOENT') return null;
    throw error;
  }
  if (metadata.isSymbolicLink()) throw new Error('environment file must not be a symlink');
  if (!metadata.isFile()) throw new Error('environment file must be a regular file');
  if ((metadata.mode & 0o077) !== 0 || (metadata.mode & 0o600) !== 0o600) {
    throw new Error('environment file permissions are insecure');
  }
  const content = await readFile(outputPath, 'utf8');
  try {
    validateCompleteEnvironment(content, 'existing environment file');
  } catch {
    throw new Error('existing environment file is incomplete');
  }
  return content;
}

async function ensurePrivateDirectory(directoryPath) {
  try {
    await mkdir(directoryPath, { mode: 0o700 });
  } catch (error) {
    if (error?.code !== 'EEXIST') throw error;
  }
  const metadata = await lstat(directoryPath);
  if (!metadata.isDirectory() || (metadata.mode & 0o077) !== 0 || (metadata.mode & 0o700) !== 0o700) {
    throw new Error('secret directory is missing or permissions are insecure');
  }
}

function hostPort(key) {
  const value = process.env[key];
  return value === undefined || value === '' ? portDefaults[key] : value;
}

function buildEnvironment() {
  const lines = [
    '# Generated by scripts/compose-up.sh on first start. Do not commit this file.',
    ...secretKeys.map((key) => `${key}=${secureSecret()}`),
    ...portKeys.map((key) => `${key}=${hostPort(key)}`),
    ''
  ];
  const content = lines.join('\n');
  validateCompleteEnvironment(content, 'generated environment file');
  return content;
}

async function syncDirectory(directoryPath) {
  const handle = await open(directoryPath, 'r');
  try {
    await handle.sync();
  } finally {
    await handle.close();
  }
}

async function publishEnvironment(outputPath, content) {
  const temporaryPath = `${outputPath}.${process.pid}.${randomBytes(8).toString('hex')}.tmp`;
  const handle = await open(temporaryPath, 'wx', 0o600);
  try {
    await handle.writeFile(content, 'utf8');
    await handle.sync();
  } finally {
    await handle.close();
  }
  try {
    await chmod(temporaryPath, 0o600);
    await link(temporaryPath, outputPath);
    await syncDirectory(dirname(outputPath));
  } finally {
    await unlink(temporaryPath).catch(() => {});
  }
}

async function seedEnvironment(outputPath) {
  const existing = await inspectEnvironmentFile(outputPath);
  if (existing !== null) return false;

  await ensurePrivateDirectory(dirname(outputPath));
  const lockPath = `${outputPath}.lock`;
  let lockHandle;
  try {
    lockHandle = await open(lockPath, 'wx', 0o600);
  } catch (error) {
    if (error?.code === 'EEXIST') throw new Error('another seed is already running; refusing to continue');
    throw error;
  }

  try {
    const afterLock = await inspectEnvironmentFile(outputPath);
    if (afterLock !== null) return false;
    await publishEnvironment(outputPath, buildEnvironment());
    return true;
  } finally {
    await lockHandle.close();
    await unlink(lockPath).catch(() => {});
  }
}

export async function main(argumentsList = process.argv.slice(2)) {
  const { outputPath } = parseArguments(argumentsList);
  const created = await seedEnvironment(outputPath);
  process.stdout.write(created ? 'created secure compose environment\n' : 'compose environment already exists; unchanged\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  main().catch((error) => {
    process.stderr.write(`seed failed: ${error.message}\n`);
    process.exitCode = 1;
  });
}
